#!/bin/bash
# 发布新版 Moru Studio：
#   1) 更新 assets/moru/release.js（Moru 助手读它判断有没有新版本）
#   2) 顺手打包一份 .dmg（打包脚本存在的话）
#   3) 打印后面的「提交 / 部署 / 上传 GitHub Releases」步骤
#
# 用法：bash scripts/release.sh <版本号> [更新说明] [dmg路径]
# 例：  bash scripts/release.sh 1.0.1 "上新：全新购物体验"

set -euo pipefail
cd "$(dirname "$0")/.."

VERSION="${1:-}"
NOTE="${2:-焕新上线，欢迎体验}"
DMG="${3:-$HOME/Documents/MORU系列/dist/Moru-Studio.dmg}"
REPO="LongYingZhang/Moru-Studio"
MANIFEST="assets/moru/release.js"

if [[ -z "$VERSION" ]]; then
  echo "用法: bash scripts/release.sh <版本号> [更新说明] [dmg路径]"
  echo "例:   bash scripts/release.sh 1.0.1 \"上新：全新购物体验\""
  exit 1
fi

mkdir -p "$(dirname "$MANIFEST")"

cat > "$MANIFEST" <<EOF
// Auto-generated by scripts/release.sh — 不要手改
// Moru 助手读取这个文件判断有没有新版本（跨域 script，免 CORS）
window.__MORU_RELEASE__ = {
  "version": "$VERSION",
  "dmgUrl": "https://github.com/$REPO/releases/download/v$VERSION/Moru-Studio.dmg",
  "note": "$NOTE",
  "publishedAt": "$(date +%Y-%m-%d)"
};
EOF

echo "✓ 已写入 $MANIFEST -> v$VERSION"

# 打包 .dmg（打包脚本存在就顺手打一份）
# 优先用原生窗口版（build-mac-app.sh），没有再退回浏览器版。
BUILD="$PWD/scripts/build-mac-app.sh"
[[ -f "$BUILD" ]] || BUILD="$PWD/scripts/build-mac-dmg.sh"
if [[ -f "$BUILD" ]]; then
  echo "→ 打包 .dmg ..."
  bash "$BUILD" "Moru Studio" "$PWD" "$DMG" || echo "（打包失败，可稍后手动打包）"
else
  echo "→ 没找到打包脚本，跳过打包；现有 .dmg：$DMG"
fi

cat <<EOF

下一步（按顺序做完，助手才会弹出下载提示）：
  1. 提交并推送 manifest：
     git add "$MANIFEST" && git commit -m "release: v$VERSION" && git push origin HEAD
  2. 部署到 Cloudflare Pages（manifest 要线上生效）：
     NPM_CONFIG_CACHE="\$HOME/.npm" script -q /dev/null bash scripts/deploy-cloudflare.sh
  3. 上传 .dmg 到 GitHub Releases（下载链接指向这里）：
     gh release create v$VERSION "$DMG" --repo "$REPO" --title "Moru Studio v$VERSION" --notes "$NOTE"

之后打开 Moru Studio，助手会自动说「上新啦 v$VERSION」，点「下载新版」即可下载 .dmg。
EOF
