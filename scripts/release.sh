#!/bin/bash
# 发布新版 Moru Studio：
#   1) 先打 dmg（打包脚本会从 release.js 读版本号写进 app）
#   2) 算出 dmg 的 sha256
#   3) 写 assets/moru/release.js（Moru 助手读它判断有没有新版本，自更新读它拿地址和校验值）
#   4) 把 dmg 放进 download/，打印后面的「提交 / 部署」步骤
#
# 用法：bash scripts/release.sh <版本号> [更新说明] [dmg路径]
# 例：  bash scripts/release.sh 1.0.9 "上市新品"

set -euo pipefail
cd "$(dirname "$0")/.."

VERSION="${1:-}"
NOTE="${2:-焕新上线，欢迎体验}"
DMG="${3:-$HOME/Documents/MORU系列/dist/Moru-Studio.dmg}"
MANIFEST="assets/moru/release.js"

if [[ -z "$VERSION" ]]; then
  echo "用法: bash scripts/release.sh <版本号> [更新说明] [dmg路径]"
  echo "例:   bash scripts/release.sh 1.0.9 \"上市新品\""
  exit 1
fi

mkdir -p "$(dirname "$MANIFEST")"
TODAY="$(date +%Y-%m-%d)"

write_manifest() {
  local sha="$1"
  cat > "$MANIFEST" <<EOF
// Auto-generated by scripts/release.sh — 不要手改
// Moru 助手读取这个文件判断有没有新版本（跨域 script，免 CORS）；
// 桌面版自更新也读它：dmgUrl 是下载地址，sha256 用来校验下到的包。
window.__MORU_RELEASE__ = {
  "version": "$VERSION",
  "dmgUrl": "https://longying-studio.pages.dev/download/Moru-Studio.dmg",
  "sha256": "$sha",
  "note": "$NOTE",
  "publishedAt": "$TODAY"
};
EOF
}

# 先写一版没有 sha 的：打包脚本要靠它拿到版本号
write_manifest ""
echo "✓ 版本写入 $MANIFEST -> v$VERSION"

# ---- 打包 -------------------------------------------------------------
BUILD="$PWD/scripts/build-mac-app.sh"
[[ -f "$BUILD" ]] || BUILD="$PWD/scripts/build-mac-dmg.sh"
if [[ -f "$BUILD" ]]; then
  echo "→ 打包 .dmg ..."
  bash "$BUILD" "Moru Studio" "$PWD" "$DMG" || echo "（打包失败，可稍后手动打包）"
else
  echo "→ 没找到打包脚本，跳过打包；现有 .dmg：$DMG"
fi

# ---- 算校验值并补进清单 ------------------------------------------------
SHA=""
if [[ -f "$DMG" ]]; then
  SHA="$(shasum -a 256 "$DMG" | awk '{print $1}')"
  write_manifest "$SHA"
  echo "✓ sha256: $SHA"
  mkdir -p download
  cp "$DMG" download/Moru-Studio.dmg
  echo "✓ 已放到 download/Moru-Studio.dmg ($(du -h download/Moru-Studio.dmg | cut -f1))"
fi

cat <<EOF

下一步（按顺序做完，助手才会弹出更新提示）：
  1. 提交并推送：
     git add -A && git commit -m "release: v$VERSION" && git push origin HEAD
  2. 部署到 Cloudflare Pages（manifest 和 dmg 都要线上生效）：
     bash scripts/deploy-cloudflare.sh
  3. 验证：
     curl -s https://longying-studio.pages.dev/assets/moru/release.js
     curl -sI https://longying-studio.pages.dev/download/Moru-Studio.dmg | head -3

之后打开 Moru Studio，气泡里会出现「Moru Studio v${VERSION}的更新已就绪」，
点一下就由 app 自己下载安装、自动重启，不会再弹「无法验证开发者」。
EOF
